#!/usr/bin/env node
// Writes src/js/34-packs.js, the content the page carries, from server/content/*.json (WS-E):
//   the schedule helpers (copied byte for byte from server/content-core.js's CLIENT block),
//   the daily-dare starters and Mole tasks, and the local Decode pack for claude.ai and local mode.
// The local pack never holds an answer in plain text (C48, C86): each puzzle has a salt, a PBKDF2 hash of
// the answer to check a guess against, and the answer sealed under a key derived from the salt, opened
// only once the week's answer is out. That's an honour system (anyone determined can run the same code),
// and it's labelled so in the app; in server mode the page the server hands out has no pack at all.
//
//   node tools/content.js           write src/js/34-packs.js
//   node tools/content.js --check   exit 1 if src/js/34-packs.js isn't a fresh build of the JSON
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const REPO = path.resolve(__dirname, '..');
const DIR = path.join(REPO, 'server', 'content');
const OUT = path.join(REPO, 'src', 'js', '34-packs.js');
const ITER = 10000;

const salt = (pack, id) => crypto.createHash('sha256').update('insane-salt|' + pack + '|' + id).digest('hex').slice(0, 16);
const hash = (answer, s) => crypto.pbkdf2Sync(answer, 'insane-decode|' + s, ITER, 16, 'sha256').toString('hex');
function seal(answer, s, id) {
  const k = crypto.createHash('sha256').update('insane-seal|' + s + '|' + id).digest();
  return Buffer.from([...Buffer.from(answer, 'latin1')].map((b, i) => b ^ k[i])).toString('base64');
}

function build() {
  const core = fs.readFileSync(path.join(REPO, 'server', 'content-core.js'), 'utf8');
  const m = /\/\* CLIENT-BEGIN \*\/\n([\s\S]*?)\/\* CLIENT-END \*\//.exec(core);
  if (!m) throw new Error('server/content-core.js: no CLIENT block');
  const P = JSON.parse(fs.readFileSync(path.join(DIR, 'puzzles.json'), 'utf8'));
  const D = JSON.parse(fs.readFileSync(path.join(DIR, 'dares.json'), 'utf8')).dares;
  const M = JSON.parse(fs.readFileSync(path.join(DIR, 'mole.json'), 'utf8')).tasks;
  M.forEach((t, i) => { if (t.i !== i) throw new Error('mole.json: task ' + i + ' has i=' + t.i + ' (indices are permanent and dense)'); });
  const local = { iter: ITER, packs: P.packs.map(p => ({ id: p.id, name: p.name, cities: p.cities, puzzles: p.puzzles.map(z => { const s = salt(p.id, z.id); return { id: z.id, q: z.q, h: z.h, s, x: hash(z.a, s), z: seal(z.a, s, z.id) }; }) })) };
  const J = v => JSON.stringify(v);
  return `/* ---------- content the page carries: generated by tools/content.js from server/content/*.json. Do not edit; edit the JSON and run node tools/content.js ---------- */
${m[1]}// daily-dare starters [text, level], Mole tasks by permanent index, and how many times each must be done
const STARTER_DARES=${J(D.map(d => [d.text, d.level]))};
const MOLE_TASKS=${J(M.map(t => t.text))};
const MOLE_N=${J(M.map(t => t.n))};
const MOLE_POOL=${J(M.map(t => t.i))};
// Decode for claude.ai and local mode: clues and hints, each answer only as a salted hash and a seal.
// The server strips this block from the page it serves (server/server.js sendIndex).
/*@decode-local*/const DECODE_LOCAL=${J(local)};/*@end-decode-local*/
`;
}

if (require.main === module) {
  const out = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { console.error('src/js/34-packs.js is stale: run node tools/content.js'); process.exit(1); }
    console.log('src/js/34-packs.js is fresh');
  } else { fs.writeFileSync(OUT, out); console.log('wrote src/js/34-packs.js', Buffer.byteLength(out), 'bytes'); }
}
module.exports = { build, salt, hash, seal, ITER, OUT };
